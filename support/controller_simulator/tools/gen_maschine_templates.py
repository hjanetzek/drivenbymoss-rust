"""Generate maschine_simulator/templates.py:

- MK2 and JAM from dbm-nihost's template tables (support/linux/ni_host/src/template_map.h, itself
  generated from the DrivenByMoss NI Controller Editor templates by tools/gen_template_map.py
  there), the MIDI dbm-nihost sends;
- MK3 and MIKRO_MK3 directly from the DrivenByMoss NI templates (resources/Maschine Mk3/
  DrivenByMoss.ncm3, resources/Maschine Mikro Mk3/DrivenByMoss.ncmm3 of the Java DrivenByMoss),
  the MIDI NI's driver sends, with the parser of gen_template_map.py; the controls the template
  disables (<disabled/>: NI's driver sends nothing for them) are listed in MK3_DISABLED and
  MIKRO_MK3_DISABLED.

tests/test_maschine.py checks that they agree with their sources.

Usage: gen_maschine_templates.py [template_map.h] [DrivenByMoss checkout] [templates.py]
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_HEADER = os.path.join(HERE, "..", "..", "linux", "ni_host", "src", "template_map.h")
DEFAULT_OUTPUT = os.path.join(HERE, "..", "maschine_simulator", "templates.py")
DEFAULT_JAVA = os.path.expanduser("~/bastel/github/DrivenByMoss")
NI_TEMPLATES = (("mk3", "resources/Maschine Mk3/DrivenByMoss.ncm3"),
                ("mikro_mk3", "resources/Maschine Mikro Mk3/DrivenByMoss.ncmm3"))
NI_HOST_TOOLS = os.path.join(HERE, "..", "..", "linux", "ni_host", "tools")

ENTRY = re.compile(r'\{ "(\w+)", Direction::(\w+), MessageKind::(\w+), (\d+), (\d+), (true|false), (\d+), (\d+) \}')


def parse(header_text: str) -> dict[str, list[tuple]]:
    tables: dict[str, list[tuple]] = {}
    current = None
    for line in header_text.splitlines():
        m = re.search(r"TemplateControl (\w+)\[\]", line)
        if m:
            current = tables.setdefault(m.group(1), [])
            continue
        m = ENTRY.search(line)
        if m and current is not None:
            ident, direction, kind, channel, number, relative, on, off = m.groups()
            current.append((ident, direction.lower(), kind.lower(), int(channel), int(number), relative == "true", int(on), int(off)))
    return tables


def parse_ni_template(path: str) -> tuple[list[tuple], list[str]]:
    """The controls of an NI template (as gen_template_map.entries) and the disabled ones."""
    import xml.etree.ElementTree as ET
    sys.path.insert(0, NI_HOST_TOOLS)
    import gen_template_map
    rows = [(e["id"], e["direction"].lower(), e["kind"].lower(), e["channel"], e["number"], e["relative"], e["on"], e["off"])
            for e in gen_template_map.entries(path)]
    midi_map = ET.parse(path).getroot().find("midi-map")
    disabled = sorted({e.get("id") for e in gen_template_map.controls(midi_map) if e.find("disabled") is not None})
    return rows, disabled


def render(tables: dict[str, list[tuple]], disabled: dict[str, list[str]] | None = None) -> str:
    out = ['# Generated by tools/gen_maschine_templates.py from support/linux/ni_host/src/template_map.h',
           '# and the DrivenByMoss NI Controller Editor templates (Mk3, Mikro Mk3) - do not edit.',
           '',
           '"""The controls of the DrivenByMoss NI templates: (id, direction "input"/"led", kind',
           '"cc"/"note"/"polyat", channel 0..15, number, relative, on value, off value)."""',
           '']
    for name, entries in tables.items():
        out.append(f"{name.upper()} = (")
        for e in entries:
            out.append(f"    {e!r},")
        out.append(")")
        out.append("")
    for name, ids in (disabled or {}).items():
        out.append(f"{name.upper()}_DISABLED = frozenset({ids!r})")
        out.append("")
    return "\n".join(out)


def main() -> int:
    header = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HEADER
    java = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_JAVA
    output = sys.argv[3] if len(sys.argv) > 3 else DEFAULT_OUTPUT
    with open(header) as f:
        tables = parse(f.read())
    disabled = {}
    for name, rel in NI_TEMPLATES:
        tables[name], disabled[name] = parse_ni_template(os.path.join(java, rel))
    with open(output, "w") as f:
        f.write(render(tables, disabled))
    print(f"{output}: " + ", ".join(f"{k} {len(v)}" for k, v in tables.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
