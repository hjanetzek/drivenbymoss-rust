"""Generate maschine_simulator/templates.py from dbm-nihost's template tables
(support/linux/ni_host/src/template_map.h, itself generated from the DrivenByMoss NI Controller
Editor templates by tools/gen_template_map.py there). tests/test_maschine.py checks that the two
agree.

Usage: gen_maschine_templates.py [template_map.h] [templates.py]
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_HEADER = os.path.join(HERE, "..", "..", "linux", "ni_host", "src", "template_map.h")
DEFAULT_OUTPUT = os.path.join(HERE, "..", "maschine_simulator", "templates.py")

ENTRY = re.compile(r'\{ "(\w+)", Direction::(\w+), MessageKind::(\w+), (\d+), (\d+), (true|false), (\d+), (\d+) \}')


def parse(header_text: str) -> dict[str, list[tuple]]:
    tables: dict[str, list[tuple]] = {}
    current = None
    for line in header_text.splitlines():
        m = re.search(r"TemplateControl (\w+)\[\]", line)
        if m:
            current = tables.setdefault(m.group(1), [])
            continue
        m = ENTRY.search(line)
        if m and current is not None:
            ident, direction, kind, channel, number, relative, on, off = m.groups()
            current.append((ident, direction.lower(), kind.lower(), int(channel), int(number), relative == "true", int(on), int(off)))
    return tables


def render(tables: dict[str, list[tuple]]) -> str:
    out = ['# Generated by tools/gen_maschine_templates.py from support/linux/ni_host/src/template_map.h',
           '# (the DrivenByMoss NI Controller Editor templates) - do not edit.',
           '',
           '"""The controls of the DrivenByMoss NI templates: (id, direction "input"/"led", kind',
           '"cc"/"note"/"polyat", channel 0..15, number, relative, on value, off value)."""',
           '']
    for name, entries in tables.items():
        out.append(f"{name.upper()} = (")
        for e in entries:
            out.append(f"    {e!r},")
        out.append(")")
        out.append("")
    return "\n".join(out)


def main() -> int:
    header = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_HEADER
    output = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUTPUT
    with open(header) as f:
        tables = parse(f.read())
    with open(output, "w") as f:
        f.write(render(tables))
    print(f"{output}: " + ", ".join(f"{k} {len(v)}" for k, v in tables.items()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
