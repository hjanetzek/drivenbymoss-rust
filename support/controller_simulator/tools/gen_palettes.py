"""Generate sim_common/palettes.py: the 128-colour velocity palette which Ableton's Push 1, Akai's
APC40 mkII and Novation's Launchpads (MkII, Pro, Pro Mk3, X, Mini Mk3) share, taken from Java
DrivenByMoss' PushColorManager.DEFAULT_PALETTE (without the DAW colours which DrivenByMoss writes
into entries 70..96 of the Push 2/3 palette). tests/test_midi_simulators.py checks it against the
Java source when that is available.

Usage: gen_palettes.py [PushColorManager.java] [palettes.py]
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_JAVA = os.path.expanduser("~/bastel/github/DrivenByMoss/src/main/java/de/mossgrabers/controller/ableton/push/controller/PushColorManager.java")
DEFAULT_OUTPUT = os.path.join(HERE, "..", "sim_common", "palettes.py")


def parse(java_text: str) -> list[tuple[int, int, int]]:
    start = java_text.index("DEFAULT_PALETTE =")
    block = java_text[start:java_text.index("};", start)]
    return [tuple(int(v, 16) for v in m) for m in re.findall(r"\{\s*0x(\w\w),\s*0x(\w\w),\s*0x(\w\w)\s*\}", block)]


def render(rgb: list[tuple[int, int, int]]) -> str:
    lines = ["# Copyright (c) 2026 Hannes Janetzek",
             "# Licensed under LGPLv3 - http://www.gnu.org/licenses/lgpl-3.0.txt",
             "",
             '"""Colour palettes shared by several simulated controllers (generated by tools/gen_palettes.py).',
             "",
             "``VELOCITY_128``: the 128-colour palette of the LED velocity of Ableton's Push 1, Akai's APC40",
             "mkII and Novation's Launchpads, from Java DrivenByMoss' ``PushColorManager.DEFAULT_PALETTE``.",
             '"""',
             "",
             "VELOCITY_128 = ("]
    for i in range(0, len(rgb), 4):
        lines.append("    " + " ".join("(0x%02X, 0x%02X, 0x%02X)," % c for c in rgb[i:i + 4]))
    lines += [")", "", "", "def velocity_rgb(index: int) -> tuple[int, int, int]:",
              "    return VELOCITY_128[index] if 0 <= index < len(VELOCITY_128) else (0, 0, 0)", ""]
    return "\n".join(lines)


def main() -> int:
    java = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_JAVA
    output = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUTPUT
    with open(java) as f:
        rgb = parse(f.read())
    if len(rgb) != 128:
        sys.exit(f"expected 128 entries, got {len(rgb)}")
    with open(output, "w") as f:
        f.write(render(rgb))
    print(output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
