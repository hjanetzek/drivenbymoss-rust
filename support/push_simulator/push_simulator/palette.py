def factory_white(index: int) -> int:
    """The white component of a palette entry before the host changed it: linear 0..254."""
    return min(255, index * 2)


class Palette:
    """128 entries (r, g, b, w); ``pending`` collects the entries written with SysEx 0x03 until
    they are applied with 0x05 (the device shows the new colours only after "re-apply")."""

    def __init__(self):
        self.entries = [(r, g, b, factory_white(i)) for i, (r, g, b) in enumerate(DEFAULT_RGB)]
        self.pending: dict[int, tuple[int, int, int, int]] = {}
        self.applied_count = 0

    def set_entry(self, index: int, r: int, g: int, b: int, w: int) -> None:
        if 0 <= index < 128:
            self.pending[index] = (r & 255, g & 255, b & 255, w & 255)

    def entry(self, index: int) -> tuple[int, int, int, int]:
        """The entry as the host reads it back (a written but not yet applied entry included)."""
        index &= 127
        return self.pending.get(index, self.entries[index])

    def apply(self) -> int:
        """Re-apply the palette (SysEx 0x05); returns the number of changed entries."""
        count = len(self.pending)
        for index, value in self.pending.items():
            self.entries[index] = value
        self.pending.clear()
        self.applied_count += 1
        return count

    def rgb(self, index: int) -> tuple[int, int, int]:
        r, g, b, _ = self.entries[index & 127]
        return (r, g, b)

    def white(self, index: int) -> int:
        return self.entries[index & 127][3]


def encode_entry_reply(index: int, entry: tuple[int, int, int, int]) -> list[int]:
    """The data bytes of a palette entry (after the command byte 0x04): index, then r, g, b, w
    each as 7 bit LSB + MSB (``ColorPaletteEntry.requiresUpdate``)."""
    data = [index & 127]
    for value in entry:
        data += [value & 127, (value >> 7) & 1]
    return data


# Push 1: the two-colour LEDs of the upper button row and the scene buttons (PUSH1_COLOR_*: 1..24
# red, orange, yellow, green in a low and a high step, each steady, slow and fast blinking)
PUSH1_ROW1_HUES = ((255, 0, 0), (255, 110, 0), (255, 220, 0), (0, 230, 0))


def push1_row1(value: int) -> tuple[tuple[int, int, int], int]:
    """Colour and blink mode (0 steady, 1 slow, 2 fast) of a Push 1 two-colour LED value."""
    if value <= 0 or value > 24:
        return ((0, 0, 0), 0)
    step, blink = divmod(value - 1, 3)
    hue, level = divmod(step, 2)
    scale = 1.0 if level else 0.35
    return (tuple(int(c * scale) for c in PUSH1_ROW1_HUES[hue]), blink)


def push1_single(value: int, base: tuple[int, int, int]) -> tuple[tuple[int, int, int], int]:
    """Colour and blink mode of a Push 1 single colour button LED (0 off, 1 dim, 2/3 dim blinking
    slow/fast, 4 lit, 5/6 lit blinking slow/fast)."""
    if value <= 0:
        return ((0, 0, 0), 0)
    if value > 6:
        value = 4
    lit = value >= 4
    blink = (value - 1) % 3
    scale = 1.0 if lit else 0.3
    return (tuple(int(c * scale) for c in base), blink)
