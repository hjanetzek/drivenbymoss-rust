"""Generates src/template_map.h from the DrivenByMoss NI Controller Editor templates.

The templates (resources/Maschine Mk2/DrivenByMoss.ncm2, resources/Maschine Jam/DrivenByMoss.ncmj)
define which MIDI message NI's driver sends for each control and which one sets each LED. Only the
active page of each paged section (current_index) is used, since the DrivenByMoss templates
disable page switching.

Usage: gen_template_map.py <repository root> <output header>
"""

import sys
import xml.etree.ElementTree as ET
from pathlib import Path

DEVICES = [
    ("mk2", "resources/Maschine Mk2/DrivenByMoss.ncm2"),
    ("jam", "resources/Maschine Jam/DrivenByMoss.ncmj"),
]

INPUT_TAGS = ("button", "knob", "wheel", "pad")


def message(element):
    """(kind, number, relative) of the MIDI message of a control element, or None."""
    for kind, tag in (("Cc", "controller"), ("Note", "note"), ("PolyAt", "polyat")):
        node = element.find(tag)
        if node is not None and node.text is not None:
            return kind, int(node.text), node.get("mode") == "comp"
    # A button in MCU mode sends a note on channel 1 (e.g. the 7th display button of the Mk2)
    node = element.find("mcu-button")
    if node is not None and node.text is not None:
        return "Note", int(node.text), False
    return None


def controls(midi_map):
    """All control elements of the controls section and of the active page of each section."""
    for section in midi_map:
        current = section.find("current_index")
        if current is None:
            # Not paged: the controls section
            yield from (e for e in section if e.tag in INPUT_TAGS or e.tag == "led")
            continue
        pages = [p for p in section if p.tag != "current_index"]
        page = pages[int(current.text)]
        yield from (e for e in page if e.tag in INPUT_TAGS or e.tag == "led")


def entries(path):
    midi_map = ET.parse(path).getroot().find("midi-map")
    result = []
    seen = set()
    for element in controls(midi_map):
        msg = message(element)
        if msg is None:
            continue
        channel = element.find("channel")
        channel = int(channel.text) if channel is not None else 0
        on = element.find("on")
        off = element.find("off")
        direction = "Led" if element.tag == "led" else "Input"
        key = (element.get("id"), direction)
        if key in seen:
            raise SystemExit(f"{path}: duplicate control {key}")
        seen.add(key)
        result.append(
            {
                "id": element.get("id"),
                "direction": direction,
                "kind": msg[0],
                "channel": channel,
                "number": msg[1],
                "relative": msg[2],
                "on": int(on.text) if on is not None else 127,
                "off": int(off.text) if off is not None else 0,
            }
        )
    return sorted(result, key=lambda e: (e["direction"], e["id"]))


def main():
    root = Path(sys.argv[1])
    out = Path(sys.argv[2])
    lines = [
        "// Generated by tools/gen_template_map.py from the DrivenByMoss NI templates - do not edit.",
        "",
        "#pragma once",
        "",
        '#include "template.h"',
        "",
        "namespace dbm::nihost::templates",
        "{",
    ]
    for name, rel in DEVICES:
        rows = entries(root / rel)
        lines.append(f"    // {rel}")
        lines.append(f"    inline constexpr TemplateControl {name}[] = {{")
        for e in rows:
            lines.append(
                f'        {{ "{e["id"]}", Direction::{e["direction"]}, MessageKind::{e["kind"]}, {e["channel"]}, '
                f'{e["number"]}, {"true" if e["relative"] else "false"}, {e["on"]}, {e["off"]} }},'
            )
        lines.append("    };")
        lines.append("")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
