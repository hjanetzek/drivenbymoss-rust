"""Generate src/framework/graphics/icon_data.rs: the SVG icons of DrivenByMoss
(src/main/resources/images) rendered at scale 1 (like Java `host.loadSVG (name, 1)`) into 8 bit
alpha masks, which the graphics context draws with a color (former `maskImage`).

Usage (from the repository root; needs `rsvg-convert` and Python with Pillow):

    python3 src/framework/graphics/tools/gen_icons.py ~/bastel/github/DrivenByMoss/src/main/resources/images \
        > src/framework/graphics/icon_data.rs
"""

import io
import os
import subprocess
import sys

from PIL import Image

ROOT = os.path.expanduser(sys.argv[1] if len(sys.argv) > 1 else '~/bastel/github/DrivenByMoss/src/main/resources/images')

# The images loaded by the Java ResourceHandler, in its order.
NAMES = [
    'channel/mute.svg', 'channel/record_arm.svg', 'channel/solo.svg',
    'track/audio_track.svg', 'track/crossfade_a.svg', 'track/crossfade_ab.svg', 'track/crossfade_b.svg',
    'track/group_track.svg', 'track/group_track_open.svg', 'track/hybrid_track.svg',
    'track/instrument_track.svg', 'track/master_track.svg', 'track/multi_layer.svg', 'track/return_track.svg',
    'device/device_analysis.svg', 'device/device_audio.svg', 'device/device_container.svg',
    'device/device_drum_machine.svg', 'device/device_drum_module.svg', 'device/device_generic.svg',
    'device/device_instrument.svg', 'device/device_io.svg', 'device/device_note.svg', 'device/device_plugin.svg',
    'pin.svg', 'user.svg',
]


def const_name(name):
    return os.path.splitext(os.path.basename(name))[0].upper()


out = sys.stdout
out.write('''// Written by Jürgen Moßgraber - mossgrabers.de
// (c) 2017-2026
// Licensed under LGPLv3 - http://www.gnu.org/licenses/lgpl-3.0.txt

//! GENERATED by `src/framework/graphics/tools/gen_icons.py` - do not edit.
//!
//! The SVG icons of DrivenByMoss (`src/main/resources/images`) rendered at scale 1 with
//! `rsvg-convert` as 8 bit alpha masks (row by row).

use super::icons::IconData;

''')
for name in NAMES:
    png = subprocess.run(['rsvg-convert', '-f', 'png', os.path.join(ROOT, name)], check=True, capture_output=True).stdout
    image = Image.open(io.BytesIO(png)).convert('RGBA')
    width, height = image.size
    channel = image.getchannel('A')
    alpha = list(channel.get_flattened_data() if hasattr(channel, 'get_flattened_data') else channel.getdata())
    rows = []
    for y in range(height):
        rows.append('        ' + ' '.join('%d,' % a for a in alpha[y * width:(y + 1) * width]))
    out.write('/// `%s`\n#[rustfmt::skip]\npub static %s: IconData = IconData {\n    name: "%s",\n    width: %d,\n    height: %d,\n    alpha: &[\n%s\n    ],\n};\n\n'
              % (name, const_name(name), name, width, height, '\n'.join(rows)))

out.write('/// All icons by their Java resource name.\npub static ALL: [&IconData; %d] = [%s];\n' % (len(NAMES), ', '.join('&' + const_name(n) for n in NAMES)))
