/// Get the glyph of a character. Characters which are not printable ASCII are drawn as '?'.
pub fn glyph(c: char) -> &'static [u8; 5] {
    let code = c as u32;
    if (0x20..0x7F).contains(&code) {
        &GLYPHS[(code - 0x20) as usize]
    } else {
        &GLYPHS[('?' as u32 - 0x20) as usize]
    }
}

/// The integer scale factor of the font which approximates the given font size (in pixels, the
/// em size of the Java fonts). The capital letters of a typical sans serif font have about 72%
/// of the em size.
pub fn scale_for_font_size(font_size: f64) -> i32 {
    ((font_size * 0.72 / CAP_HEIGHT as f64).round() as i32).max(1)
}

/// The width of a text in pixels with the given scale factor.
pub fn text_width(text: &str, scale: i32) -> i32 {
    let count = text.chars().count() as i32;
    if count == 0 {
        0
    } else {
        (count * ADVANCE - 1) * scale
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_and_sizes() {
        assert_eq!(glyph('T'), &[0x01, 0x01, 0x7F, 0x01, 0x01]);
        assert_eq!(glyph('ü'), glyph('?'));
        assert_eq!(scale_for_font_size(20.0), 2);
        assert_eq!(scale_for_font_size(5.0), 1);
        assert_eq!(text_width("", 2), 0);
        assert_eq!(text_width("AB", 1), 11);
        assert_eq!(text_width("AB", 2), 22);
    }
}
