/// `ChannelVolumeStr` → `channel_volume_str`.
fn snake(name: &str) -> String {
    upper_snake(name).to_lowercase()
}

/// The Python expression of an index slot of a writer method.
fn py_slot_value(slot: &IdxSlot) -> String {
    match slot.as_slice() {
        [p] if p.bits == 16 => if p.signed { format!("{} & 0xFFFF", p.name) } else { p.name.clone() },
        parts => parts.iter().map(|p| format!("({} & {}) << {}", p.name, part_mask(p), p.shift)).collect::<Vec<_>>().join(" | "),
    }
}

/// The Python metadata tuple of the slots.
fn py_slots(slots: &[IdxSlot]) -> String {
    let parts: Vec<String> = slots
        .iter()
        .map(|slot| {
            let parts: Vec<String> = slot.iter().map(|p| format!("(\"{}\", {}, {}, {})", p.name, p.shift, p.bits, if p.signed { "True" } else { "False" })).collect();
            format!("({},)", parts.join(", "))
        })
        .collect();
    if parts.is_empty() {
        "()".into()
    } else {
        format!("({},)", parts.join(", "))
    }
}

