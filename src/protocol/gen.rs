/// The C++ type of a value type for the writers and views.
fn cpp_value(t: u8) -> Option<(&'static str, &'static str)> {
    // (parameter type, view accessor)
    match t {
        ty::BOOL => Some(("bool", "record.boolValue ()")),
        ty::I32 => Some(("int32_t", "record.intValue ()")),
        ty::F64 => Some(("double", "record.doubleValue ()")),
        ty::TEXT => Some(("const std::string &", "record.text ()")),
        ty::COLOR => Some(("Color", "record.color ()")),
        ty::TEXT_LIST => Some(("const std::vector<std::string> &", "record.textList ()")),
        _ => None,
    }
}

fn cpp_view_type(t: u8) -> &'static str {
    match t {
        ty::BOOL => "bool",
        ty::I32 => "int32_t",
        ty::F64 => "double",
        ty::TEXT => "std::string",
        ty::COLOR => "Color",
        ty::TEXT_LIST => "std::vector<std::string>",
        _ => "",
    }
}

/// The C++ expression of an index slot of a writer method: the parameter, or the packed parts.
fn cpp_slot_value(slot: &IdxSlot) -> String {
    match slot.as_slice() {
        [p] if p.bits == 16 => if p.signed { format!("static_cast<uint16_t> ({})", p.name) } else { p.name.clone() },
        parts => format!("static_cast<uint16_t> ({})", parts.iter().map(|p| format!("(({} & {}u) << {})", p.name, part_mask(p), p.shift)).collect::<Vec<_>>().join(" | ")),
    }
}

