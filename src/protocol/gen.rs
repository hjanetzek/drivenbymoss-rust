/// `ChannelVolumeStr` → `CHANNEL_VOLUME_STR`.
fn upper_snake(name: &str) -> String {
    let mut out = String::new();
    let chars: Vec<char> = name.chars().collect();
    for (i, c) in chars.iter().enumerate() {
        let next_lower = chars.get(i + 1).is_some_and(|n| n.is_lowercase());
        if i > 0 && c.is_uppercase() && (chars[i - 1].is_lowercase() || chars[i - 1].is_ascii_digit() || next_lower) && chars[i - 1] != '_' {
            out.push('_');
        }
        out.push(c.to_ascii_uppercase());
    }
    out
}

/// `ChannelVolumeStr` → `channelVolumeStr`.
fn lower_camel(name: &str) -> String {
    let mut chars = name.chars();
    chars.next().map(|c| c.to_ascii_lowercase().to_string() + chars.as_str()).unwrap_or_default()
}

/// The name of an index slot: the field, or `field_slot` for a field with several slots.
fn slot_name(field: &str, slot: &str) -> String {
    if slot.is_empty() {
        field.to_string()
    } else {
        format!("{field}_{slot}")
    }
}

