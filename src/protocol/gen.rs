/// The messages and commands: (name, ID, template, index slots, value type).
struct Entry {
    name: &'static str,
    id: u16,
    template: String,
    slots: Vec<IdxSlot>,
    value_type: u8,
    /// The value kind of the Python binding ([`py_kind`]).
    kind: &'static str,
}

/// The value kind of a value field (the Rust type of the table) for the Python binding: how the
/// value is read and written.
fn py_kind(rust_type: Option<&str>) -> &'static str {
    let Some(t) = rust_type else { return "none" };
    match t.replace(' ', "").replace("'a", "").as_str() {
        "bool" | "Enable" => "bool",
        "i32" | "IntText" | "Pos1" | "ChannelType" | "RecordQuantization" => "i32",
        "f64" => "f64",
        "&str" => "text",
        "Vec<&str>" => "text_list",
        "Option<[f64;3]>" | "Rgb" => "color",
        "Vec<Note>" => "notes",
        "Option<StepInfo>" => "step",
        "ValueOp" => "value_op",
        "Signature" | "SlotRef" => "pair",
        "GridNote" | "StepValue" => "int_double",
        other => panic!("no Python value kind for {other}"),
    }
}

/// The Rust type of the value field of an entry.
fn value_rust_type(fields: &'static [(&'static str, &'static str)], value: Option<&'static str>) -> Option<&'static str> {
    let value = value?;
    fields.iter().find(|(name, _)| *name == value).map(|(_, t)| *t)
}

fn messages() -> Vec<Entry> {
    MESSAGES
        .iter()
        .map(|info| Entry {
            name: info.name,
            id: info.id as u16,
            template: info.template.to_string(),
            slots: info.id.index_slots(),
            value_type: info.id.value_type(),
            kind: py_kind(value_rust_type(info.fields, info.value)),
        })
        .collect()
}

fn commands() -> Vec<Entry> {
    COMMANDS
        .iter()
        .map(|info| {
            let processor = match info.processor {
                super::ProcSpec::Fixed(p) => p.id().to_string(),
                super::ProcSpec::Field(f) => format!("{{{f}}}"),
            };
            Entry {
                name: info.name,
                id: info.id as u16,
                template: format!("{processor} {}", info.template),
                slots: info.id.index_slots(),
                value_type: info.id.value_type(),
                kind: py_kind(value_rust_type(info.fields, info.value)),
            }
        })
        .collect()
}

