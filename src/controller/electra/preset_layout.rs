//! The controls of the pages of the DrivenByMoss preset (`DrivenByMoss.eproj` of the Java
//! version): the kind, the name and the color of each control as the preset defines them,
//! generated from the preset. The surface link (`link`) needs them for the controls which the
//! modes do not update (e.g. the names of the transport pads), and for the kind of each slot
//! (a knob at CC `10 + 10 * row + column` or a pad at CC `70 + 10 * row + column`).

use crate::framework::surface_link::SlotKind;

/// A control of the preset.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PresetControl {
    pub kind: SlotKind,
    pub name: &'static str,
    /// RRGGBB
    pub color: &'static str,
    /// The number of entries of a list.
    pub steps: u32,
}

const fn c(kind: SlotKind, name: &'static str, color: &'static str, steps: u32) -> PresetControl {
    PresetControl { kind, name, color, steps }
}

