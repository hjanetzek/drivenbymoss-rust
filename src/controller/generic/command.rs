//! All available Flexi commands and their categories (former `FlexiCommand` and
//! `CommandCategory`).
//!
//! Generated from the Java enums (same order, so the ordinals are the same). The handlers use
//! the ordinals for the numbered commands, e.g. `command.ordinal() - FlexiCommand::Track1SetVolume.ordinal()`.

/// The category of a command (former `CommandCategory`). Each category has one handler.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum CommandCategory {
    Browser,
    Clip,
    Device,
    FunctionLayers,
    Groove,
    InstrumentDevice,
    Eq,
    FxTrack,
    Global,
    Layer,
    Layout,
    Marker,
    Master,
    MidiCc,
    Modes,
    NoteInput,
    ProjectRemotes,
    Scene,
    Track,
    TrackRemotes,
    Transport,
    Action,
}

impl CommandCategory {
    /// All categories in the order of the Java enum.
    pub const ALL: [CommandCategory; 22] = [
        CommandCategory::Browser,
        CommandCategory::Clip,
        CommandCategory::Device,
        CommandCategory::FunctionLayers,
        CommandCategory::Groove,
        CommandCategory::InstrumentDevice,
        CommandCategory::Eq,
        CommandCategory::FxTrack,
        CommandCategory::Global,
        CommandCategory::Layer,
        CommandCategory::Layout,
        CommandCategory::Marker,
        CommandCategory::Master,
        CommandCategory::MidiCc,
        CommandCategory::Modes,
        CommandCategory::NoteInput,
        CommandCategory::ProjectRemotes,
        CommandCategory::Scene,
        CommandCategory::Track,
        CommandCategory::TrackRemotes,
        CommandCategory::Transport,
        CommandCategory::Action,
    ];

    /// The name of the category.
    pub fn name(self) -> &'static str {
        match self {
            CommandCategory::Browser => "Browser",
            CommandCategory::Clip => "Clip",
            CommandCategory::Device => "Device",
            CommandCategory::FunctionLayers => "Function Layers",
            CommandCategory::Groove => "Groove",
            CommandCategory::InstrumentDevice => "1st Instrument Device",
            CommandCategory::Eq => "EQ",
            CommandCategory::FxTrack => "FX Track",
            CommandCategory::Global => "Global",
            CommandCategory::Layer => "Layer",
            CommandCategory::Layout => "Layout",
            CommandCategory::Marker => "Marker",
            CommandCategory::Master => "Master",
            CommandCategory::MidiCc => "MIDI CC",
            CommandCategory::Modes => "Modes",
            CommandCategory::NoteInput => "Note Input",
            CommandCategory::ProjectRemotes => "Project Remotes",
            CommandCategory::Scene => "Scene",
            CommandCategory::Track => "Track",
            CommandCategory::TrackRemotes => "Track Remotes",
            CommandCategory::Transport => "Transport",
            CommandCategory::Action => "Action",
        }
    }

    /// The index of the category in [`CommandCategory::ALL`].
    pub fn ordinal(self) -> usize {
        self as usize
    }
}

