# Generates one Bitwig extension definition class per controller of the Rust core, and the
# services file which lists them. Bitwig only finds definitions as Java classes, so this runs
# whenever controllers are added to the core:
#
#   backends/bitwig/tools/gen_definitions.py          (from the rust/ directory)
#
# The controller data comes from `cargo run --bin dbm-catalog` (see dbm_list_controllers). The
# definitions get their own UUIDs (derived from the core's), so that the extension can be
# installed next to the Java DrivenByMoss, which uses the core's UUIDs.

import json
import os
import re
import subprocess
import sys
import uuid

PACKAGE = "de.mossgrabers.dbm.bitwig.definitions"
NAMESPACE = uuid.UUID("6d9c3a52-6f0e-4c39-9a51-2f0b0e1d2b7a")

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CRATE = os.path.dirname(os.path.dirname(ROOT))
SOURCE_DIR = os.path.join(ROOT, "src", "main", "java", *PACKAGE.split("."))
SERVICES = os.path.join(ROOT, "src", "main", "resources", "META-INF", "services", "com.bitwig.extension.ExtensionDefinition")

# The probe extension of the conformance tests (doc/CONFORMANCE_TESTING_PLAN.md)
EXTRA_DEFINITIONS = ["de.mossgrabers.dbm.bitwig.ProbeExtensionDefinition"]

HEADER = """// Generated by tools/gen_definitions.py from the controllers of the Rust core. Do not edit.
// Licensed under LGPLv3 - http://www.gnu.org/licenses/lgpl-3.0.txt

"""


def java_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def java_pairs(pairs):
    """The discovery pairs as Java code: new String [][][] { { { inputs }, { outputs } }, ... }."""
    items = []
    for pair in pairs:
        inputs = ", ".join(java_string(name) for name in pair["inputs"])
        outputs = ", ".join(java_string(name) for name in pair["outputs"])
        items.append("{ { " + inputs + " }, { " + outputs + " } }")
    if not items:
        return "new String [0][][]"
    return "new String [][][]\n        {\n            " + ",\n            ".join(items) + "\n        }"


def class_name(controller):
    words = re.findall(r"[A-Za-z0-9]+", controller["vendor"] + " " + controller["model"])
    return "".join(word[0].upper() + word[1:] for word in words) + "Definition"


def main():
    catalog = json.loads(subprocess.check_output(["cargo", "run", "-q", "--bin", "dbm-catalog"], cwd=CRATE))
    os.makedirs(SOURCE_DIR, exist_ok=True)
    for name in os.listdir(SOURCE_DIR):
        if name.endswith("Definition.java"):
            os.remove(os.path.join(SOURCE_DIR, name))

    classes = []
    for controller in catalog:
        name = class_name(controller)
        own_id = uuid.uuid5(NAMESPACE, controller["uuid"].upper())
        discovery = controller["discovery"]
        code = HEADER + f"""package {PACKAGE};

import de.mossgrabers.dbm.bitwig.DbmExtensionDefinition;


/**
 * {controller["vendor"]} {controller["model"]}.
 */
public final class {name} extends DbmExtensionDefinition
{{
    /**
     * Constructor.
     */
    public {name} ()
    {{
        super ({java_string(str(own_id))}, {java_string(controller["uuid"])}, {java_string(controller["vendor"])}, {java_string(controller["model"])}, {controller["numMidiInPorts"]}, {controller["numMidiOutPorts"]},
        // Windows
        {java_pairs(discovery["windows"])},
        // Linux
        {java_pairs(discovery["linux"])},
        // macOS
        {java_pairs(discovery["mac"])});
    }}
}}
"""
        with open(os.path.join(SOURCE_DIR, name + ".java"), "w") as file:
            file.write(code)
        classes.append(f"{PACKAGE}.{name}")

    # Hand-written extensions which are not controllers of the core
    classes.extend(EXTRA_DEFINITIONS)

    os.makedirs(os.path.dirname(SERVICES), exist_ok=True)
    with open(SERVICES, "w") as file:
        file.write("\n".join(sorted(classes)) + "\n")
    print(f"Generated {len(classes)} definitions", file=sys.stderr)


if __name__ == "__main__":
    main()
